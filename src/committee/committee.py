# Default fallback if symbol lacks optimized data
DEFAULT_SCORE_THRESHOLD = settings.DEFAULT_SCORE_THRESHOLD

# Alias for tests / external imports — the real trade-gating threshold is
# DEFAULT_SCORE_THRESHOLD (0.15) or the per-symbol adaptive threshold.
WINNING_SCORE_THRESHOLD = DEFAULT_SCORE_THRESHOLD

_THRESHOLDS_CACHE = {}
_THRESHOLDS_LAST_LOAD = 0.0


def get_symbol_threshold(symbol: str) -> float:
    """Lazily load and cache the adaptive thresholds JSON generated by the weekly analyzer."""
    global _THRESHOLDS_CACHE, _THRESHOLDS_LAST_LOAD
    now = time.time()
    
    # Reload every 5 minutes to pick up weekly analyzer updates automatically
    if now - _THRESHOLDS_LAST_LOAD > 300:
        thresh_file = os.path.join(os.path.dirname(__file__), '..', '..', 'data', 'adaptive_thresholds.json')
        if os.path.exists(thresh_file):
            try:
                with open(thresh_file) as f:
                    _THRESHOLDS_CACHE = json.load(f)
            except Exception as e:
                logger.warning(f"Failed to load adaptive thresholds: {e}")
        _THRESHOLDS_LAST_LOAD = now
        
    return float(_THRESHOLDS_CACHE.get(symbol, DEFAULT_SCORE_THRESHOLD))

# Process-wide adaptive meta-learner singleton. Loaded lazily and fail-safe:
# any construction/load error leaves the committee on its classic behavior.
_META_LEARNER: AdaptiveMetaLearner | None = None


def get_meta_learner() -> AdaptiveMetaLearner | None:
    """Return the cached adaptive learner, constructing it lazily (fail-safe)."""
    global _META_LEARNER
    if _META_LEARNER is None:
        try:
            _META_LEARNER = AdaptiveMetaLearner(
                state_path=settings.ADAPTIVE_STATE_PATH,
                learning_rate=settings.ADAPTIVE_LEARNING_RATE,
                min_weight=settings.ADAPTIVE_MIN_WEIGHT,
                max_weight=settings.ADAPTIVE_MAX_WEIGHT,
            )
        except Exception as e:  # pragma: no cover - defensive
            logger.warning(f"Adaptive meta-learner unavailable, using classic committee: {e}")
            _META_LEARNER = None
    return _META_LEARNER


def reset_meta_learner() -> None:
    """Drop the cached learner so the next call reloads from current settings/state.

    Primarily used by tests and after out-of-band state updates.
    """
    global _META_LEARNER
    _META_LEARNER = None

